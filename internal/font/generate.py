@dataclass(frozen=True)
class Number:
    raw: str

    @property
    def integer(self) -> int:
        return int(self.raw, 0)

    @property
    def floating(self) -> float:
        return float(self.raw)


@dataclass(frozen=True)
class Reference:
    name: str


class Parser:
    def __init__(self, text: str, pos: int = 0):
        self.text = text
        self.pos = pos

    def skip(self) -> None:
        while self.pos < len(self.text):
            match = re.match(r"\s+", self.text[self.pos :])
            if match:
                self.pos += match.end()
                continue
            if self.text.startswith("//", self.pos):
                end = self.text.find("\n", self.pos + 2)
                self.pos = len(self.text) if end < 0 else end + 1
                continue
            if self.text.startswith("/*", self.pos):
                end = self.text.find("*/", self.pos + 2)
                if end < 0:
                    raise ValueError("unterminated comment")
                self.pos = end + 2
                continue
            break

    def peek(self) -> str:
        self.skip()
        return self.text[self.pos : self.pos + 1]

    def take(self, value: str) -> None:
        self.skip()
        if not self.text.startswith(value, self.pos):
            raise ValueError(f"expected {value!r} at offset {self.pos}")
        self.pos += len(value)

    def identifier(self) -> str:
        self.skip()
        match = re.match(r"[A-Za-z_$][A-Za-z0-9_$]*", self.text[self.pos :])
        if not match:
            raise ValueError(f"expected identifier at offset {self.pos}")
        self.pos += match.end()
        return match.group(0)

    def number(self) -> Number:
        self.skip()
        match = re.match(
            r"-?(?:0[xX][0-9A-Fa-f]+|(?:(?:\d+(?:\.\d*)?)|(?:\.\d+))(?:[eE][+-]?\d+)?)",
            self.text[self.pos :],
        )
        if not match:
            raise ValueError(f"expected number at offset {self.pos}")
        self.pos += match.end()
        return Number(match.group(0))

    def string(self) -> str:
        self.skip()
        quote = self.text[self.pos]
        start = self.pos
        self.pos += 1
        escaped = False
        while self.pos < len(self.text):
            char = self.text[self.pos]
            self.pos += 1
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == quote:
                return ast.literal_eval(self.text[start : self.pos])
        raise ValueError(f"unterminated string at offset {start}")

    def value(self) -> Any:
        self.skip()
        char = self.peek()
        if char == "{":
            return self.object()
        if char == "[":
            return self.array()
        if char in ("'", '"'):
            return self.string()
        if char == "-" or char == "." or char.isdigit():
            return self.number()
        name = self.identifier()
        if name == "true":
            return True
        if name == "false":
            return False
        if name in ("null", "undefined"):
            return None
        return Reference(name)

    def array(self) -> list[Any]:
        values: list[Any] = []
        self.take("[")
        while self.peek() != "]":
            # TypeScript's sparse arrays occur outside this tranche, but
            # accepting holes makes the literal parser deterministic.
            if self.peek() == ",":
                values.append(None)
                self.take(",")
                continue
            values.append(self.value())
            if self.peek() != ",":
                break
            self.take(",")
        self.take("]")
        return values

    def object(self) -> dict[Any, Any]:
        values: dict[Any, Any] = {}
        self.take("{")
        while self.peek() != "}":
            char = self.peek()
            if char in ("'", '"'):
                key: Any = self.string()
            elif char == "-" or char == "." or char.isdigit():
                number = self.number()
                key = number.integer
            else:
                key = self.identifier()
            self.take(":")
            values[key] = self.value()
            if self.peek() != ",":
                break
            self.take(",")
        self.take("}")
        return values


def resolve(value: Any, environment: dict[str, Any]) -> Any:
    if isinstance(value, Reference):
        if value.name not in environment:
            raise ValueError(f"unknown literal reference {value.name}")
        return copy.deepcopy(environment[value.name])
    if isinstance(value, list):
        return [resolve(item, environment) for item in value]
    if isinstance(value, dict):
        return {key: resolve(item, environment) for key, item in value.items()}
    return value


def exported_object(text: str) -> dict[int, Any]:
    match = re.search(r"export\s+const\s+\w+\s*:[^=]+?=\s*", text)
    if not match:
        raise ValueError("exported object was not found")
    value = Parser(text, match.end()).value()
    if not isinstance(value, dict):
        raise ValueError("exported value is not an object")
    return value


def svg_objects(text: str) -> tuple[dict[int, str], dict[int, str]]:
    marker = "AddPaths(font,"
    start = text.find(marker)
    if start < 0:
        return {}, {}
    parser = Parser(text, start + len(marker))
    paths = parser.value()
    if not isinstance(paths, dict):
        raise ValueError("SVG path argument is not an object")
    content: dict[int, str] = {}
    if parser.peek() == ",":
        parser.take(",")
        if parser.peek() == "{":
            content = parser.value()
    return paths, content


def delimiter_object(text: str) -> dict[int, Any]:
    environment: dict[str, Any] = {"V": "V", "H": "H"}
    declaration = re.compile(r"(?:export\s+)?const\s+(\w+)\s*(?::[^=]+)?=\s*")
    delimiters: dict[int, Any] | None = None
    for match in declaration.finditer(text):
        name = match.group(1)
        value = Parser(text, match.end()).value()
        value = resolve(value, environment)
        environment[name] = value
        if name == "delimiters":
            delimiters = value
    if delimiters is None:
        raise ValueError("delimiter map was not found")
    return delimiters


def go_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True, separators=(",", ":"))


# Lengths are stored as integers in units of 1/10000 em. MathJax writes them
# with at most four decimals, and float64(n)/10000 is then the same double as
# the decimal literal: both are the correctly rounded value of n/10000.
LENGTH_UNIT = 10000
NO_OPTION = -(1 << 15)


def length_units(number: Number) -> int:
    scaled = Decimal(number.raw) * LENGTH_UNIT
    units = int(scaled)
    if scaled != units:
        raise ValueError(f"{number.raw} has more than four decimals")
    if not NO_OPTION < units < (1 << 15):
        raise ValueError(f"{number.raw} does not fit a 16-bit length")
    if float(units) / LENGTH_UNIT != number.floating:
        raise ValueError(f"{number.raw} does not survive scaling by {LENGTH_UNIT}")
    return units


def glyph_metrics(values: list[Any]) -> list[int]:
    """Return height, depth, width, italic correction and skew in length units."""
    if len(values) not in (3, 4):
        raise ValueError(f"unexpected CharData length {len(values)}")
    units = [length_units(value) for value in values[:3]] + [NO_OPTION, NO_OPTION]
    if len(values) == 4:
        options = values[3]
        unknown = set(options) - {"ic", "sk"}
        if unknown:
            raise ValueError(f"unsupported CharOptions: {sorted(unknown)}")
        if "ic" in options:
            units[3] = length_units(options["ic"])
        if "sk" in options:
            units[4] = length_units(options["sk"])
    return units


def go_table(values: list[str], per_line: int) -> list[str]:
    return [
        "\t" + ", ".join(values[start : start + per_line]) + ",\n"
        for start in range(0, len(values), per_line)
    ]


def write_glyphs(
    output: Path,
    tables: list[tuple[str, str, dict[int, list[Any]], dict[int, str], dict[int, str]]],
) -> None:
    """Write every variant's glyphs as pointer-free tables.

    A Go map of structs costs a hash bucket slot, a string header and a
    garbage-collector root per glyph. Sorted code points, integer metrics and
    one shared string avoid all three.
    """
    starts = [0]
    codepoints: list[tuple[str, list[int]]] = []
    metric_rows: list[tuple[str, list[tuple[int, list[int]]]]] = []
    string_of_glyph: list[int] = []
    # Index 0 is the empty outline. Outlines come first and substitution
    # strings after them, so one index says which of the two a glyph has.
    path_index: dict[str, int] = {"": 0}
    path_list: list[str] = [""]
    content_index: dict[str, int] = {}
    content_list: list[str] = []
    pending_content: list[tuple[int, str]] = []
    for source_name, go_name, metrics, paths, content in tables:
        if set(paths) & set(content):
            raise ValueError(f"{source_name}: path and content maps overlap")
        if set(metrics) != set(paths) | set(content):
            missing = sorted(set(metrics) - set(paths) - set(content))
            extra = sorted((set(paths) | set(content)) - set(metrics))
            raise ValueError(f"{source_name}: SVG coverage mismatch missing={missing[:5]} extra={extra[:5]}")
        ordered = sorted(metrics)
        if any(codepoint < 0 or codepoint > 0x10FFFF for codepoint in ordered):
            raise ValueError(f"{source_name}: code point out of range")
        codepoints.append((go_name, ordered))
        metric_rows.append((go_name, [(codepoint, glyph_metrics(metrics[codepoint])) for codepoint in ordered]))
        for codepoint in ordered:
            if codepoint in content:
                text = content[codepoint]
                if text == "":
                    raise ValueError(f"{source_name}: empty substitution for U+{codepoint:04X}")
                if text not in content_index:
                    content_index[text] = len(content_list)
                    content_list.append(text)
                pending_content.append((len(string_of_glyph), text))
                string_of_glyph.append(-1)
            else:
                text = paths[codepoint]
                if text not in path_index:
                    path_index[text] = len(path_list)
                    path_list.append(text)
                string_of_glyph.append(path_index[text])
        starts.append(starts[-1] + len(ordered))
    first_content = len(path_list)
    for glyph, text in pending_content:
        string_of_glyph[glyph] = first_content + content_index[text]
    strings = path_list + content_list
    if starts[-1] >= 1 << 16 or len(strings) >= 1 << 16:
        raise ValueError("glyph or string count does not fit 16 bits")
    offsets = [0]
    for text in strings:
        offsets.append(offsets[-1] + len(text.encode("utf-8")))

    lines = [
        GENERATED_HEADER,
        "// The glyphs of all variants, in the order of the variants array and by\n",
        "// increasing code point within a variant. Glyph i of the tables below belongs\n",
        "// to variant v when glyphVariantStart[v] <= i < glyphVariantStart[v+1].\n",
        "var glyphVariantStart = [...]uint16{\n",
    ]
    lines.extend(go_table([str(value) for value in starts], 12))
    lines.append("}\n\n")

    lines.append("// glyphCodepoints holds the code point of every glyph.\n")
    lines.append("var glyphCodepoints = [...]uint32{\n")
    for go_name, ordered in codepoints:
        lines.append(f"\t// {go_name}\n")
        lines.extend(go_table([f"0x{codepoint:X}" for codepoint in ordered], 12))
    lines.append("}\n\n")

    lines.extend((
        "// na marks an italic correction or skew that the source does not give.\n",
        f"const na = {NO_OPTION}\n\n",
        "// glyphMetrics holds five lengths per glyph: height, depth, width, italic\n",
        f"// correction and skew, in units of 1/{LENGTH_UNIT} em.\n",
        "var glyphMetrics = [...]int16{\n",
    ))
    for go_name, rows in metric_rows:
        lines.append(f"\t// {go_name}\n")
        for codepoint, units in rows:
            values = ", ".join("na" if value == NO_OPTION else str(value) for value in units)
            lines.append(f"\t/* {codepoint:X} */ {values},\n")
    lines.append("}\n\n")

    lines.extend((
        "// glyphStrings holds the index of every glyph's string. Strings below\n",
        "// glyphFirstContent are SVG outlines; the others are the characters MathJax\n",
        "// draws in place of an outline (the `c` option).\n",
        "var glyphStrings = [...]uint16{\n",
    ))
    lines.extend(go_table([str(value) for value in string_of_glyph], 16))
    lines.append("}\n\n")
    lines.append(f"const glyphFirstContent = {first_content}\n\n")

    lines.append("// String s is glyphStringData[glyphStringOffsets[s]:glyphStringOffsets[s+1]].\n")
    lines.append("var glyphStringOffsets = [...]uint32{\n")
    lines.extend(go_table([str(value) for value in offsets], 12))
    lines.append("}\n\n")

    lines.append('const glyphStringData = "" +\n')
    nonempty = [text for text in strings if text != ""]
    for position, text in enumerate(nonempty):
        ending = "\n" if position == len(nonempty) - 1 else " +\n"
        lines.append(f"\t{go_string(text)}{ending}")
    (output / "data_glyphs_gen.go").write_text("".join(lines))


def delimiter_record(data: dict[str, Any]) -> list[int]:
    """Encode one DelimiterData as 16-bit words; delimiter.go has the layout."""
    allowed = {"dir", "sizes", "variants", "schar", "stretch", "stretchv", "HDW", "min", "c", "fullExt"}
    unknown = set(data) - allowed
    if unknown:
        raise ValueError(f"unsupported DelimiterData: {sorted(unknown)}")

    def word(value: int) -> int:
        if not 0 <= value < 1 << 16:
            raise ValueError(f"{value} does not fit a 16-bit delimiter word")
        return value

    def lengths(values: list[Number]) -> list[int]:
        return [length_units(value) & 0xFFFF for value in values]

    def integers(values: list[Number]) -> list[int]:
        return [word(value.integer) for value in values]

    flags = {"V": 0, "H": 1}[data["dir"]]
    lists = [
        lengths(data.get("sizes", [])),
        integers(data.get("variants", [])),
        integers(data.get("schar", [])),
        integers(data.get("stretch", [])),
        integers(data.get("stretchv", [])),
    ]
    counts = 0
    for position, values in enumerate(lists):
        if len(values) > 7:
            raise ValueError("delimiter list longer than seven entries")
        counts |= len(values) << (3 * position)
    tail: list[int] = []
    if "HDW" in data:
        if len(data["HDW"]) != 3:
            raise ValueError("HDW must have three entries")
        flags |= 1 << 1
        tail += lengths(data["HDW"])
    if "min" in data:
        flags |= 1 << 2
        tail += lengths([data["min"]])
    if "c" in data:
        flags |= 1 << 3
        tail += integers([data["c"]])
    if "fullExt" in data:
        if len(data["fullExt"]) != 2:
            raise ValueError("fullExt must have two entries")
        flags |= 1 << 4
        tail += lengths(data["fullExt"])
    return [flags, counts] + [value for values in lists for value in values] + tail


def write_delimiters(output: Path, delimiters: dict[int, dict[str, Any]]) -> None:
    ordered = sorted(delimiters)
    if any(not 0 <= codepoint < 1 << 16 for codepoint in ordered):
        raise ValueError("delimiter code point does not fit 16 bits")
    records = [delimiter_record(delimiters[codepoint]) for codepoint in ordered]
    offsets = [0]
    for record in records:
        offsets.append(offsets[-1] + len(record))
    if offsets[-1] >= 1 << 16:
        raise ValueError("delimiter data does not fit 16-bit offsets")
    lines = [
        GENERATED_HEADER,
        "// delimiterCodepoints holds the stretchy delimiters in increasing order.\n",
        "var delimiterCodepoints = [...]uint16{\n",
    ]
    lines.extend(go_table([f"0x{codepoint:X}" for codepoint in ordered], 12))
    lines.extend((
        "}\n\n",
        "// The record of delimiter i is delimiterData[delimiterOffsets[i]:delimiterOffsets[i+1]].\n",
        "var delimiterOffsets = [...]uint16{\n",
    ))
    lines.extend(go_table([str(value) for value in offsets], 12))
    lines.extend((
        "}\n\n",
        "// delimiterData holds one record per line; decodeDelimiter documents the layout.\n",
        "var delimiterData = [...]uint16{\n",
    ))
    for codepoint, record in zip(ordered, records):
        values = ", ".join(f"0x{value:X}" if position < 2 else str(value) for position, value in enumerate(record))
        lines.append(f"\t/* {codepoint:X} */ {values},\n")
    lines.append("}\n")
    (output / "data_delimiters_gen.go").write_text("".join(lines))


def source_hash(files: list[Path], root: Path) -> str:
    digest = hashlib.sha256()
    for path in sorted(files):
        digest.update(path.relative_to(root).as_posix().encode())
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def write_registry(output: Path, hashes: tuple[str, str, str]) -> None:
    lines = [
        GENERATED_HEADER,
        "// Source hashes cover sorted relative names, NUL, exact source bytes, and NUL.\n",
        f'const CommonSourceSHA256 = "{hashes[0]}"\n',
        f'const SVGSourceSHA256 = "{hashes[1]}"\n',
        f'const DelimiterSourceSHA256 = "{hashes[2]}"\n',
    ]
    (output / "data_registry_gen.go").write_text("".join(lines))


def find_source(argument: str | None, output: Path) -> Path:
    candidates: list[Path] = []
    if argument:
        candidates.append(Path(argument))
    if os.environ.get("MATHJAX_SRC"):
        candidates.append(Path(os.environ["MATHJAX_SRC"]))
    candidates.append((output / "../../../../work/mathjax-src-3.2.2").resolve())
    for candidate in candidates:
        if (candidate / "ts/output/common/fonts/tex/normal.ts").is_file():
            return candidate / "ts/output"
        if (candidate / "common/fonts/tex/normal.ts").is_file():
            return candidate
    raise SystemExit("MathJax 3.2.2 source not found; pass --source or set MATHJAX_SRC")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", help="MathJax checkout root or its ts/output directory")
    parser.add_argument("--output", help="generated package directory")
    args = parser.parse_args()

    output = Path(args.output).resolve() if args.output else Path(__file__).resolve().parent
    source = find_source(args.source, output)
    common_dir = source / "common/fonts/tex"
    svg_dir = source / "svg/fonts/tex"

    for stale in output.glob("data_*_gen.go"):
        stale.unlink()

    common_files: list[Path] = []
    svg_files: list[Path] = []
    tables = []
    for _, source_name, go_name in VARIANTS:
        common_path = common_dir / f"{source_name}.ts"
        svg_path = svg_dir / f"{source_name}.ts"
        common_files.append(common_path)
        svg_files.append(svg_path)
        metrics = exported_object(common_path.read_text())
        paths, content = svg_objects(svg_path.read_text())
        tables.append((source_name, go_name, metrics, paths, content))
    write_glyphs(output, tables)

    delimiter_path = common_dir / "delimiters.ts"
    delimiters = delimiter_object(delimiter_path.read_text())
    write_delimiters(output, delimiters)
    write_registry(
        output,
        (
            source_hash(common_files, source),
            source_hash(svg_files, source),
            source_hash([delimiter_path], source),
        ),
    )
    print(f"generated {sum(len(exported_object(path.read_text())) for path in common_files)} glyphs and {len(delimiters)} delimiters", file=sys.stderr)


if __name__ == "__main__":
    main()
